#!/usr/bin/env bash
#
# Единственное, что разрешено ключу машины-хранилища на прод-сервере.
# Прописывается принудительной командой в ~/.ssh/authorized_keys (это делает
# infra/backup/allow-pull.sh), поэтому выполнить здесь что-либо другое —
# оболочку, копирование, удаление — этим ключом нельзя.
#
# Разрешены две команды, и обе только отдают данные:
#
#   snapshot-db      зашифрованный дамп базы в stdout
#   snapshot-media   зашифрованный архив фотографий в stdout
#
# Копии на сервере не хранятся: снимок делается в момент запроса и уходит
# потоком, не касаясь диска. Поэтому здесь нечего перечислять и нечего
# удалять — команд `list` и `fetch` больше нет.
#
# Направление (хранилище забирает, а не сервер отправляет) выбрано затем,
# чтобы на сервере не лежал ключ с правом записи в архив: иначе тот, кто
# получил сервер, стёр бы вместе с ним и копии — ровно то, ради чего их
# вывозят наружу.
set -euo pipefail

DIR="${NOOVA_DIR:-$HOME/noova}"
STREAM="$DIR/infra/backup/stream.sh"

deny() { printf 'pull-guard: %s\n' "$1" >&2; exit 1; }

# Аргументов нет ни у одной команды, поэтому сравниваем строку целиком:
# ничего из присланного не попадает ни в путь, ни в команду.
case "${SSH_ORIGINAL_COMMAND:-}" in
	snapshot-db)    WHAT=db ;;
	snapshot-media) WHAT=media ;;
	*) deny "разрешены только snapshot-db и snapshot-media" ;;
esac

[ -f "$STREAM" ] || deny "нет $STREAM — на сервере не хватает файлов: make deploy-files"

# Пульс: когда хранилище в последний раз забрало эту копию ЦЕЛИКОМ. Его читает
# watch.sh — сторож на проде, который поднимает тревогу, если хранилище
# перестало приходить (выключено, сломан крон, не тот адрес). Проверять это
# с самого хранилища бессмысленно: ровно тогда оно и молчит. Отдельный от
# каталога стека путь — выкладка (`make deploy`) его не трогает.
#
# Без `exec`, чтобы успеть записать пульс после потока. Код возврата
# передаём как есть: оборванная выдача пульса не обновляет.
STATE="${NOOVA_BACKUP_STATE:-$HOME/.noova-backup}"
if /usr/bin/env bash "$STREAM" "$WHAT"; then
	umask 077
	mkdir -p "$STATE"
	date +%s > "$STATE/last-$WHAT.tmp" && mv "$STATE/last-$WHAT.tmp" "$STATE/last-$WHAT"
else
	exit 1
fi
