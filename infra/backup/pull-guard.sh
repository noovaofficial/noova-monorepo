#!/usr/bin/env bash
#
# Доступ «только на чтение» к каталогу копий для машины-хранилища.
#
# Прописывается принудительной командой в ~/.ssh/authorized_keys прод-сервера
# (это делает infra/backup/allow-pull.sh), поэтому ключ хранилища не может
# выполнить здесь ничего, кроме двух команд ниже — ни оболочки, ни записи,
# ни удаления.
#
# Зачем так: копии забирает хранилище, а не прод их отправляет. При обратном
# направлении ключ для отправки лежал бы на проде, и тот, кто получил прод,
# получил бы вместе с ним и право стереть архив — то есть ровно то, от чего
# копии и вывозят наружу.
set -euo pipefail

DIR="${NOOVA_BACKUPS:-$HOME/noova/backups}"

deny() { printf 'pull-guard: %s\n' "$1" >&2; exit 1; }

CMD="${SSH_ORIGINAL_COMMAND:-}"
ACTION="${CMD%% *}"
ARG="${CMD#* }"
# Команда без аргумента: обрезание по пробелу вернуло её же.
if [ "$ARG" = "$CMD" ]; then ARG=""; fi

case "$ACTION" in
	list)
		cd "$DIR" 2>/dev/null || deny "нет каталога $DIR"
		shopt -s nullglob
		# Размер рядом с именем: по нему хранилище отличает докачанный файл
		# от оборванного, не доверяя самому факту существования файла.
		for F in noova-*.enc; do
			printf '%s %s\n' "$(stat -c '%s' "$F")" "$F"
		done
		;;
	fetch)
		# Имя проверяем списком разрешённых символов, а не поиском «../»:
		# при таком наборе `/` невозможен в принципе, и выйти из каталога
		# просто нечем.
		case "$ARG" in
			''|*[!A-Za-z0-9._-]*) deny "недопустимое имя" ;;
		esac
		case "$ARG" in
			noova-*.enc) ;;
			*) deny "разрешены только noova-*.enc" ;;
		esac
		[ -f "$DIR/$ARG" ] || deny "нет файла $ARG"
		cat "$DIR/$ARG"
		;;
	*)
		deny "разрешены только list и fetch"
		;;
esac
