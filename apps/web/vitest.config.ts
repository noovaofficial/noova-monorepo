import { fileURLToPath } from 'node:url';
import { defineConfig } from 'vitest/config';

/**
 * До появления тестов компонентов конфига здесь не было вовсе: словарные
 * проверки обходятся относительными импортами и умолчаниями vitest.
 *
 * JSX здесь не настраивается: vitest 4 трансформирует через oxc, а тот уже
 * использует автоматический рантайм. Переданные ему настройки esbuild он
 * молча игнорирует — с предупреждением в шапке прогона, которое легко
 * принять за шум.
 */
export default defineConfig({
  // Псевдоним `@` — тот же, что в tsconfig. Без него компонент, импортирующий
  // `@/shared/...`, не соберётся в тесте, хотя в приложении работает.
  resolve: {
    alias: { '@': fileURLToPath(new URL('./src', import.meta.url)) },
  },
  /**
   * JSX разворачивается здесь, потому что в `tsconfig.json` стоит
   * `jsx: "preserve"` — так требует Next, у которого свой трансформер.
   * Трансформер тестов эту настройку слушается и оставляет JSX в выводе,
   * после чего Vite падает на «invalid JS syntax». Настройка нужна именно
   * `oxc`: vitest 4 перешёл на него, а переданные esbuild-настройки молча
   * игнорирует.
   */
  oxc: { jsx: { runtime: 'automatic' } },
  test: {
    /**
     * DOM только там, где он нужен. Словарные проверки и тесты чистых функций
     * работают быстрее без него, а `environmentMatchGlobs` уже убран из
     * vitest — поэтому окружение выбирается построчной директивой
     * `@vitest-environment jsdom` в шапке файла.
     */
    environment: 'node',
    globals: false,
    // Каждый тест компонента оставляет за собой DOM; без очистки следующий
    // рендер находит два экземпляра и `getByRole` падает на неоднозначности.
    setupFiles: ['./src/test/setup.ts'],
  },
});
