import { cleanup } from '@testing-library/react';
import { afterEach } from 'vitest';

/**
 * Размонтирование после каждого теста. Без него деревья копятся в одном и том
 * же документе, и `getByRole` падает не потому, что компонент сломан, а
 * потому, что нашёл два. Ошибка при этом указывает на невиновный тест —
 * тот, что шёл вторым.
 *
 * В окружении `node` DOM-а нет, и вызывать нечего: `cleanup` там же и
 * упадёт, поэтому проверяем окружение, а не полагаемся на удачу.
 */
afterEach(() => {
  if (typeof document !== 'undefined') cleanup();
});
