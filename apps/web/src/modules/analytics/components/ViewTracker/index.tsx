'use client';

import { useEffect, useRef } from 'react';
import { trackProfileView } from '@/modules/analytics/api';

/**
 * Маяк просмотра анкеты.
 *
 * Считать просмотры на сервере нельзя: страница анкеты отдаётся из кэша
 * (ISR, `revalidate = 600`), и её код выполняется заметно реже, чем её
 * открывают. Отдельный запрос из браузера — единственный способ узнать,
 * сколько человек анкету на самом деле видели.
 *
 * Компонент ничего не рисует. Он висит на странице анкеты и стоит одного
 * запроса на заход; повторы в пределах получаса схлопывает сервер, поэтому
 * ни дедупликации, ни хранения в браузере здесь нет.
 */
export function ViewTracker({ slug }: { slug: string }) {
  // React в режиме разработки монтирует эффекты дважды, а навигация внутри
  // приложения может вернуть на ту же анкету. Ссылка на последний
  // отправленный slug дешевле, чем полагаться на серверную дедупликацию:
  // тот запрос всё равно ушёл бы и всё равно занял бы место в лимите.
  const sent = useRef<string | null>(null);

  useEffect(() => {
    if (sent.current === slug) return;
    sent.current = slug;
    void trackProfileView(slug);
  }, [slug]);

  return null;
}
