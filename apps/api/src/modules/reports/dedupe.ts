/**
 * Сдерживание потока жалоб на одну анкету без требования входа.
 *
 * Жалоба остаётся анонимной (см. комментарий в routes.ts), поэтому защита —
 * не в том, кто пишет, а в том, сколько незакрытых жалоб может накопиться:
 *
 *  1. Один отправитель — одна незакрытая жалоба на анкету. Отправитель — это
 *     учётная запись, если человек вошёл, иначе адрес (IPv6 — подсеть /64).
 *     Повторная молча принимается и не сохраняется.
 *  2. Потолок незакрытых жалоб на анкету — от пула адресов. Модератору для
 *     решения хватит и десяти одинаковых сообщений; сотня в очереди только
 *     закрывает собой остальные анкеты.
 *
 * Срочные (несовершеннолетие, принуждение) считаются отдельно и с потолком
 * выше: обычная жалоба не должна «занять место» срочной ни у отправителя, ни
 * у анкеты. Ответ во всех случаях одинаковый — 201: отправителю незачем
 * знать, что его сообщение отброшено.
 */
export const MAX_OPEN_REPORTS = { regular: 10, urgent: 30 } as const;

export type ReportDecision = 'store' | 'duplicate' | 'full';

export function reportDecision(input: {
  /** Срочная ли новая жалоба. */
  urgent: boolean;
  /** Есть ли у этого отправителя незакрытая жалоба того же класса. */
  senderHasOpen: boolean;
  /** Сколько незакрытых жалоб того же класса у анкеты всего. */
  openCount: number;
}): ReportDecision {
  if (input.senderHasOpen) return 'duplicate';
  const limit = input.urgent ? MAX_OPEN_REPORTS.urgent : MAX_OPEN_REPORTS.regular;
  return input.openCount >= limit ? 'full' : 'store';
}
