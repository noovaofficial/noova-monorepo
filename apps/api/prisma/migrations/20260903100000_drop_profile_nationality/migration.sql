-- Свободная строка о происхождении, оставшаяся с первой версии. Из API и
-- интерфейса убрана давно (см. N-11 в constraints.md): происхождение — особая
-- категория по ст. 9 GDPR, и заменено оно самодекларируемым `appearanceType`.
-- Держать неиспользуемую колонку особой категории нельзя: пользы ноль, а
-- обязательства по ней те же, что по заполненной.

-- Предохранитель. На стенде колонка пуста, но прод — другая база, и `DROP
-- COLUMN` необратим: восстановить придётся из бэкапа, потеряв всё, что
-- случилось после него. Найдутся данные — миграция откажется идти, и это
-- правильный исход: решать, что с ними делать, должен человек, а не молчаливый
-- DDL.
DO $$
DECLARE filled bigint;
BEGIN
  SELECT count("nationality") INTO filled FROM "Profile";
  IF filled > 0 THEN
    RAISE EXCEPTION
      'Profile.nationality: % непустых значений. Колонка содержит данные особой категории — выгрузите и удалите их осознанно, затем повторите миграцию.',
      filled;
  END IF;
END $$;

-- AlterTable
ALTER TABLE "Profile" DROP COLUMN "nationality";
