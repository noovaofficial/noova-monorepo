import { describe, expect, it } from 'vitest';
import { DEFAULT_MODERATOR_ADJUST_LIMIT_GC, isAdjustWithinLimit } from './billing';

/**
 * Предел разовой корректировки баланса для модератора.
 *
 * Проверка живёт в общем пакете, потому что нужна дважды: сервер ею
 * отказывает, форма кабинета ею гасит кнопку. Разъедься эти два места —
 * сотрудник нажимал бы на доступную кнопку и получал отказ, а причину искал
 * бы в чём угодно, кроме суммы.
 */
describe('предел корректировки', () => {
  it('у админа предела нет', () => {
    expect(isAdjustWithinLimit(1_000_000, null)).toBe(true);
    expect(isAdjustWithinLimit(-1_000_000, null)).toBe(true);
  });

  it('пропускает сумму ровно по границе', () => {
    // Граница включительно: «не больше 500» значит, что 500 провести можно.
    expect(isAdjustWithinLimit(500, 500)).toBe(true);
    expect(isAdjustWithinLimit(501, 500)).toBe(false);
  });

  it('ограничивает списание так же, как начисление', () => {
    // Ограничь мы только выдачу — предел обходился бы обнулением чужого
    // баланса, а это ровно та дверь, ради которой он и вводился.
    expect(isAdjustWithinLimit(-500, 500)).toBe(true);
    expect(isAdjustWithinLimit(-501, 500)).toBe(false);
  });

  it('при нулевом пределе не пропускает ничего, кроме нуля', () => {
    // Ноль в настройке — способ временно отобрать право, не трогая код.
    expect(isAdjustWithinLimit(1, 0)).toBe(false);
    expect(isAdjustWithinLimit(-1, 0)).toBe(false);
  });

  it('умолчание заметно меньше годового тарифа агентства', () => {
    // Смысл предела: модератор отвечает на обращение в поддержку, а не
    // распоряжается деньгами проекта. Подними умолчание выше — и оно
    // перестанет что-либо ограничивать.
    expect(DEFAULT_MODERATOR_ADJUST_LIMIT_GC).toBeLessThan(5990);
  });
});
